#!/usr/bin/env bash
# RLSentry one-time setup on YOUR machine. Idempotent: safe to re-run; finished steps are skipped.
#
# Can be run by you or by a local Claude Code session, EXCEPT the signing-key creation, which
# must be done by you in a real terminal (the passphrase is what stops any agent from signing).
#
# Usage:
#   bash host/bootstrap.sh                          # GitHub repo via `gh` (private, named rlsentry)
#   bash host/bootstrap.sh --remote git@github.com:me/rlsentry.git
#   bash host/bootstrap.sh --refreeze               # after YOU edited harness/SPEC: retest, commit, push, retag
# Options: --repo-name NAME  --no-push  --allow-empty-passphrase (tests only; defeats the human gate)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KEY="${RLSENTRY_KEY:-$HOME/.ssh/rlsentry_approval_ed25519}"
REMOTE="" ; REPO_NAME="rlsentry" ; PUSH=1 ; REFREEZE=0 ; ALLOW_EMPTY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --remote) REMOTE="$2"; shift 2;;
    --repo-name) REPO_NAME="$2"; shift 2;;
    --no-push) PUSH=0; shift;;
    --refreeze) REFREEZE=1; shift;;
    --allow-empty-passphrase) ALLOW_EMPTY=1; shift;;
    *) echo "unknown option $1"; exit 2;;
  esac
done

# Windows: runs in Git Bash (bundled with Git for Windows). No WSL needed.
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) WIN=1;; *) WIN=0;; esac
pick_python() {   # python3 on macOS/Linux; python or the py launcher on Windows
  for c in python3 python "py -3"; do
    if $c -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' >/dev/null 2>&1; then echo "$c"; return 0; fi
  done
  return 1
}

step() { printf '\n\033[1m[%s] %s\033[0m\n' "$1" "$2"; }
ok()   { printf '  ✓ %s\n' "$1"; }
die()  { printf '  ✗ %s\n' "$1" >&2; exit 1; }
human(){ printf '\n  ⚠ HUMAN STEP — run this yourself in a terminal, then re-run bootstrap:\n    %s\n' "$1"; exit 3; }

cd "$REPO"

# A Claude Code session opened INSIDE this repo loads its hooks and becomes the "architect":
# the Stop hook would keep it running and the guards would block setup. Open the parent folder.
if [[ "${CLAUDE_PROJECT_DIR:-}" == "$REPO" ]]; then
  die "Claude Code was opened inside the repo. Open the PARENT folder in VS Code and run: bash $(basename "$REPO")/host/bootstrap.sh"
fi

step 1 "Prerequisites"
for c in git ssh-keygen; do command -v "$c" >/dev/null || die "$c not found (Windows: install Git for Windows and use Git Bash)"; done
PY="$(pick_python)" || die "Python 3.10+ not found (Windows: install from python.org and tick 'Add python.exe to PATH')"
if ! $PY -c "import pytest, yaml" 2>/dev/null; then
  $PY -m pip install --user --quiet pytest pyyaml || $PY -m pip install --user --quiet --break-system-packages pytest pyyaml
fi
ok "git, ssh-keygen, $PY, pytest, pyyaml"

step 2 "SPEC present"
[[ -f docs/SPEC.md ]] && ! head -1 docs/SPEC.md | grep -q SPEC-PLACEHOLDER || die "docs/SPEC.md missing or placeholder"
ok "docs/SPEC.md ($(wc -l < docs/SPEC.md) lines)"

step 3 "Approval signing key (passphrase-protected, human only)"
if [[ ! -f "$KEY" ]]; then
  human "ssh-keygen -t ed25519 -f $KEY -C rlsentry-approval     # choose a passphrase; do NOT add it to ssh-agent"
fi
if ssh-keygen -y -P "" -f "$KEY" >/dev/null 2>&1; then
  if [[ $ALLOW_EMPTY -eq 1 ]]; then
    printf '  ! key has NO passphrase: any process on this machine (including agents) could sign approvals\n'
  else
    human "ssh-keygen -p -f $KEY      # add a passphrase; an unprotected key lets agents approve their own work"
  fi
else
  ok "key $KEY is passphrase-protected"
fi

step 4 "allowed_signers (public key frozen with the harness)"
PRINCIPAL="$(git config user.email 2>/dev/null || echo rlsentry-approver)"
WANT="$PRINCIPAL namespaces=\"rlsentry-approval\" $(cat "$KEY.pub")"
if [[ "$(grep -v '^#' harness/allowed_signers 2>/dev/null | head -1)" != "$WANT" ]]; then
  printf '# Public key allowed to sign milestone approvals (generated by host/bootstrap.sh)\n%s\n' "$WANT" > harness/allowed_signers
  ok "written for $PRINCIPAL"
else
  ok "already configured"
fi

step 5 "Harness self-test"
if [[ $WIN -eq 1 ]]; then
  ok "skipped on Windows (the tests assume a POSIX shell); they run in the cloud as the first Stage 0 step"
else
  $PY -m pytest -q harness/tests || die "harness tests failed; fix before freezing"
fi
find . -name __pycache__ -prune -exec rm -rf {} + ; rm -rf .pytest_cache

step 6 "Git repository and frozen commit"
[[ -d .git ]] || git init -q -b main
git add -A
if ! git diff --cached --quiet; then
  git commit -q -m "$([[ $REFREEZE -eq 1 ]] && echo 'harness: refreeze' || echo 'frozen harness')"
  ok "committed $(git rev-parse --short HEAD)"
else
  ok "nothing new to commit ($(git rev-parse --short HEAD))"
fi

step 7 "GitHub remote"
if ! git remote get-url origin >/dev/null 2>&1; then
  if [[ -n "$REMOTE" ]]; then
    git remote add origin "$REMOTE"
  elif command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then
    gh repo create "$REPO_NAME" --private --source . --remote origin >/dev/null
  elif [[ $PUSH -eq 1 ]]; then
    die "no origin: pass --remote <url>, or install and log in to the GitHub CLI (gh auth login)"
  fi
fi
if [[ $PUSH -eq 1 ]]; then
  git push -q -u origin HEAD
  ok "pushed to $(git remote get-url origin)"
else
  ok "push skipped (--no-push)"
fi

step 8 "harness-frozen tag (LOCAL ONLY — never push it)"
git tag -f harness-frozen HEAD >/dev/null
ok "harness-frozen -> $(git rev-parse --short HEAD)"

cat <<EOF

────────────────────────────────────────────────────────────────────────
Done locally. Remaining steps happen in the browser (they cannot be scripted):

  1. https://github.com/apps/claude  → install the Claude GitHub App on this repository.
  2. https://claude.ai/code → environment selector → new environment:
       • Setup script: paste the contents of  $REPO/cloud/setup.sh
       • Network: Trusted (if Supabase images fail to pull in Stage 0, use a custom
         allowlist and add public.ecr.aws)
       • No secrets in environment variables.
  3. Start a session on this repo with that environment and send:
       Stage 0：先執行 make harness-test，再只執行 STAGE0 milestone，完成後產出驗證清單並暫停。
  4. When it pauses, run:   bash host/review.sh STAGE0 <session-branch>
────────────────────────────────────────────────────────────────────────
EOF
